// Iconos como componentes de React: cada función recibe `className` (para
// que el CSS de quien lo use controle tamaño y color con `width`/`height`/
// `color`) y devuelve un <svg>. `stroke="currentColor"` hace que el icono
// tome el color de texto del elemento que lo contiene, sin tener que
// repetir el color en cada uso.
//
// Se usan iconos dibujados en vez de emojis porque un emoji lo dibuja cada
// sistema operativo a su manera (Windows, macOS, Android...) y no se puede
// cambiar su color; un SVG se ve igual en todas partes y hereda el color
// del texto.

export function IconReloj({ className }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <circle cx="12" cy="12" r="9" />
      <polyline points="12 7 12 12 16 14" />
    </svg>
  );
}

